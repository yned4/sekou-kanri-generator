import unicodedata


def _n(s: str) -> str:
    """正規化: 半角カナ→全角、全角スペース除去、括弧統一（全角→半角）"""
    s = unicodedata.normalize("NFKC", str(s))
    s = re.sub(r"[\s\u3000\r\n]+", "", s)
    return s.strip()


